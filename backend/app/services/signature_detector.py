def _extract_all_text(img: Image.Image) -> str:
    """Extract all text-bearing metadata from the image as a single lowercase string."""
    chunks: list[str] = []

    # PNG text chunks
    if hasattr(img, "text") and img.text:
        for k, v in img.text.items():
            chunks.append(f"{k} {v}")

    # EXIF
    try:
        exif_bytes = img.info.get("exif", b"")
        if exif_bytes:
            exif_data = piexif.load(exif_bytes)
            for ifd in exif_data.values():
                if isinstance(ifd, dict):
                    for tag_val in ifd.values():
                        if isinstance(tag_val, bytes):
                            try:
                                chunks.append(tag_val.decode("utf-8", errors="ignore"))
                            except Exception:
                                pass
                        elif isinstance(tag_val, str):
                            chunks.append(tag_val)
    except Exception:
        pass

    # XMP (embedded as raw string in JPEG/PNG info)
    xmp = img.info.get("XML:com.adobe.xmp", "") or img.info.get("xmp", "")
    if xmp:
        chunks.append(xmp if isinstance(xmp, str) else xmp.decode("utf-8", errors="ignore"))

    return " ".join(chunks).lower()


def detect_provenance(image_bytes: bytes) -> dict[str, Any]:
    """
    Run Stage 1 provenance analysis.

    Returns a dict compatible with ProvenanceResult.
    """
    try:
        img = Image.open(io.BytesIO(image_bytes))
    except Exception as exc:
        return {
            "status": "error",
            "provider": None,
            "indicator_type": None,
            "confidence": 0.0,
            "explanation": f"Could not open image for provenance analysis: {exc}",
            "details": {},
        }

    combined_text = _extract_all_text(img)
    matches: list[dict] = []

    for entry in SIGNATURE_REGISTRY:
        for pattern in entry["patterns"]:
            if pattern in combined_text:
                matches.append(entry)
                break  # one match per provider is enough

    if not matches:
        return {
            "status": "no_indicator_found",
            "provider": None,
            "indicator_type": None,
            "confidence": 0.05,
            "explanation": (
                "No recognised AI-generation or provenance indicator was detected in the image metadata. "
                "Absence of a provenance indicator does not confirm the image is authentic — "
                "metadata can be stripped or may never have been present."
            ),
            "details": {"checked_registry_entries": len(SIGNATURE_REGISTRY)},
        }

    # Use the highest-reliability match as the primary result
    primary = max(matches, key=lambda m: m["reliability"])
    all_providers = [m["provider"] for m in matches]

    return {
        "status": "indicator_found",
        "provider": primary["provider"],
        "indicator_type": primary["type"],
        "confidence": primary["reliability"],
        "explanation": (
            f"A potential AI-generation indicator associated with '{primary['provider']}' was detected "
            f"in the image's metadata. {primary['explanation']} "
            "This is a forensic signal — it indicates the image may have been AI-generated or processed, "
            "but does not constitute definitive proof."
        ),
        "details": {
            "matched_providers": all_providers,
            "total_matches": len(matches),
        },
    }
